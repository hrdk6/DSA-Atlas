"""Build + test DSA Atlas content.

    python tools/build.py

1. Packs tools/pyruntime/{prelude,tracer}.py into data/pyruntime.js
   (the exact code Pyodide runs in the browser).
2. Loads every problem from tools/content/p_*.py and the study plans.
3. Runs every solution against its example(s) and records a trace of the
   example, using the same api_run the browser uses.
4. Extracts runnable code blocks from data/lessons/*.js (via node) and tests them.
5. Writes data/problems.js. Exits with status 1 if anything fails.
"""
import glob
import importlib
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOOLS = os.path.join(ROOT, 'tools')


def load_runtime():
    with open(os.path.join(TOOLS, 'pyruntime', 'prelude.py'), encoding='utf-8') as f:
        prelude = f.read()
    with open(os.path.join(TOOLS, 'pyruntime', 'tracer.py'), encoding='utf-8') as f:
        tracer = f.read()
    setup = 'PRELUDE_SRC = ' + repr(prelude) + '\n' + tracer
    ns = {'__name__': 'dsa_runtime'}
    exec(compile(setup, '<setup>', 'exec'), ns)
    return setup, ns['api_run']


def write_js(path, header, payload):
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(header)
        f.write(payload)
        f.write('\n')


def main():
    only = set(a for a in sys.argv[1:] if a.isdigit())
    setup, api_run = load_runtime()
    write_js(os.path.join(ROOT, 'data', 'pyruntime.js'),
             '/* Generated by tools/build.py: Python prelude + tracer that run in the browser. */\n'
             'window.DSA = window.DSA || {};\nDSA.PY_SETUP = ',
             json.dumps(setup, ensure_ascii=False) + ';')

    sys.path.insert(0, os.path.join(TOOLS, 'content'))
    import _base  # noqa: E402
    for path in sorted(glob.glob(os.path.join(TOOLS, 'content', 'p_*.py'))):
        importlib.import_module(os.path.splitext(os.path.basename(path))[0])
    import plans  # noqa: E402
    problems = _base.PROBLEMS

    failures = []
    for plan_id, plan in plans.PLANS.items():
        for cat in plan['categories']:
            for pid in cat['ids']:
                if pid not in problems:
                    failures.append(f'[{plan_id}] {cat["name"]}: missing problem {pid}')
                else:
                    problems[pid].setdefault('plans', [])
                    if plan_id not in problems[pid]['plans']:
                        problems[pid]['plans'].append(plan_id)

    tested = 0
    for pid in sorted(problems):
        if only and str(pid) not in only:
            continue
        p = problems[pid]
        cases = [(p['run'], p['expect'])] + [tuple(t) for t in p['tests']]
        for drv, exp in cases:
            r = json.loads(api_run(p['code'], drv, 'run', 0, exp))
            tested += 1
            if not r['ok'] or r['match'] is not True:
                failures.append(f'#{pid} {p["title"]}: driver {drv!r} expected {exp} got {r.get("value")} {r.get("error") or ""}'.strip())
        tr = json.loads(api_run(p['code'], p['run'], 'trace', 1200, p['expect']))
        p['traceSteps'] = len(tr.get('steps') or [])
        if not tr['ok']:
            failures.append(f'#{pid} {p["title"]}: trace failed: {tr.get("error")}')
        elif p['traceSteps'] == 0:
            failures.append(f'#{pid} {p["title"]}: trace recorded no steps')

    # lesson code blocks (needs node)
    lesson_blocks = 0
    try:
        out = subprocess.run(['node', os.path.join(TOOLS, 'extract_lessons.js')], capture_output=True, text=True, encoding='utf-8', cwd=ROOT, timeout=60)
        if out.returncode != 0:
            failures.append('lesson extraction failed: ' + out.stderr.strip()[:500])
        else:
            for blk in json.loads(out.stdout or '[]'):
                lesson_blocks += 1
                r = json.loads(api_run(blk['code'], blk['run'], 'run', 0, blk.get('expect')))
                bad = (not r['ok']) or (blk.get('expect') not in (None, '') and r['match'] is not True)
                if bad:
                    failures.append(f'lesson {blk["lesson"]} / {blk.get("title") or "code"}: expected {blk.get("expect")} got {r.get("value")} {r.get("error") or ""}'.strip())
                if blk.get('run'):
                    tr = json.loads(api_run(blk['code'], blk['run'], 'trace', 1200, blk.get('expect')))
                    if not tr['ok']:
                        failures.append(f'lesson {blk["lesson"]} / {blk.get("title") or "code"}: trace failed: {tr.get("error")}')
    except FileNotFoundError:
        print('note: node not found, lesson code blocks were not tested')

    out_problems = {}
    for pid, p in problems.items():
        q = {k: v for k, v in p.items() if k not in ('tests',) and v is not None}
        out_problems[str(pid)] = q
    plans_out = {}
    for plan_id, plan in plans.PLANS.items():
        plans_out[plan_id] = plan
    write_js(os.path.join(ROOT, 'data', 'problems.js'),
             '/* Generated by tools/build.py from tools/content. Every solution here passed its tests. */\n'
             'window.DSA = window.DSA || {};\n',
             'DSA.problems = ' + json.dumps(out_problems, ensure_ascii=False, indent=0) + ';\nDSA.plans = ' + json.dumps(plans_out, ensure_ascii=False) + ';')

    total = len(problems)
    print(f'problems: {total}  test cases run: {tested}  lesson code blocks: {lesson_blocks}')
    big = sorted(((p['traceSteps'], pid) for pid, p in problems.items() if p.get('traceSteps')), reverse=True)[:5]
    print('largest traces:', ', '.join(f'#{pid}={n}' for n, pid in big))
    if failures:
        print(f'\n{len(failures)} FAILURE(S):')
        for f in failures:
            print('  - ' + f)
        sys.exit(1)
    print('all checks passed')


if __name__ == '__main__':
    main()
